#!/usr/bin/env python3
"""
Bootstraps a cross-encoder training set from BharatMatrix's own documents,
before enough real usage has piled up in rerank_feedback (the implicit-
feedback table the app already logs to and exports nightly — see
download_feedback.mjs in this folder for that side of the dataset).

For each sampled chunk, Gemini is asked to write ONE question that chunk
genuinely answers — the same "generate a grounded question" trick the
Evaluation harness could use, just run offline against the chunk table
instead of at request time. That (question, chunk) pair is a positive
example; a chunk from a *different* document, and (when available) a
different chunk from the *same* document, become negatives for that same
question — a plausible-but-wrong passage and a same-document decoy,
which is the closer, harder kind of negative.

Output is JSONL in exactly the schema the real feedback export already
uses ({"question", "passage", "label"}) so combine_and_split.py can just
concatenate the two files.

Honest limits of this approach, worth keeping in mind:
- This is synthetic bootstrapping data, not human-labeled ground truth —
  it teaches the model "does this passage plausibly answer this
  question," generated by the same kind of model it's meant to replace.
  It's a reasonable cold-start when real usage hasn't produced enough
  rerank_feedback rows yet, not a permanent substitute for it.
- This pulls chunks across every ready document in the database,
  regardless of which user uploaded them. Fine for a single-operator
  demo/project database; if this ever runs against a database with other
  people's real documents, add `where d.user_id = '<your-id>'` to the
  query below rather than training on content you don't have a reason
  to use.

Usage:
    pip install "psycopg[binary]" requests
    export DATABASE_URL=postgres://...      # same one Vercel/the app uses
    export GEMINI_API_KEY=...               # same one the app uses
    python generate_synthetic_data.py --limit 250 --out synthetic.jsonl
"""

import argparse
import json
import os
import random
import sys
import time
import urllib.request
import urllib.error

try:
    import psycopg
except ImportError:
    sys.exit('Missing dependency: pip install "psycopg[binary]"')

# Same model the app itself uses for generation (src/lib/gemini.ts,
# CHAT_MODEL) — not the embedding model, which is a different endpoint.
CHAT_MODEL = "gemini-3.5-flash-lite"
GEMINI_URL = (
    f"https://generativelanguage.googleapis.com/v1beta/models/"
    f"{CHAT_MODEL}:generateContent"
)

QUESTION_PROMPT = """You are helping build training data for a document \
question-answering system. Read the passage below, taken from a real \
document. Write exactly one specific, realistic question that this \
passage directly and fully answers — the kind of question someone \
reading this document might actually ask. Do not ask something the \
passage only partially answers or merely mentions in passing.

Respond with ONLY a JSON object: {{"question": "..."}}

Passage:
\"\"\"
{passage}
\"\"\"
"""


def call_gemini(api_key: str, passage: str, retries: int = 3) -> str | None:
    body = json.dumps(
        {
            "contents": [
                {"role": "user", "parts": [{"text": QUESTION_PROMPT.format(passage=passage[:2000])}]}
            ],
            "generationConfig": {
                "responseMimeType": "application/json",
                "temperature": 0.4,
            },
        }
    ).encode("utf-8")

    req = urllib.request.Request(
        f"{GEMINI_URL}?key={api_key}",
        data=body,
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    for attempt in range(retries):
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                data = json.loads(resp.read())
            text = data["candidates"][0]["content"]["parts"][0]["text"]
            question = json.loads(text).get("question", "").strip()
            return question or None
        except urllib.error.HTTPError as e:
            if e.code == 429 and attempt < retries - 1:
                time.sleep(5 * (attempt + 1))
                continue
            print(f"  [gemini error {e.code}]", file=sys.stderr)
            return None
        except Exception as e:  # noqa: BLE001 — this is a one-shot script, log and move on
            print(f"  [gemini error] {e}", file=sys.stderr)
            return None
    return None


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--limit", type=int, default=250, help="Max chunks to generate questions for")
    parser.add_argument("--out", default="synthetic.jsonl")
    parser.add_argument("--db-url", default=os.environ.get("DATABASE_URL"))
    parser.add_argument("--api-key", default=os.environ.get("GEMINI_API_KEY"))
    parser.add_argument("--sleep", type=float, default=1.2, help="Seconds between Gemini calls (free-tier rate limit)")
    parser.add_argument("--quiet", action="store_true",
                        help="don't print generated questions (use in CI: public repos have public logs)")
    args = parser.parse_args()

    if not args.db_url:
        sys.exit("Set DATABASE_URL (or pass --db-url).")
    if not args.api_key:
        sys.exit("Set GEMINI_API_KEY (or pass --api-key).")

    print("Connecting to the database…")
    conn = psycopg.connect(args.db_url)
    with conn.cursor() as cur:
        cur.execute(
            """
            select c.id, c.document_id, c.content
            from document_chunks c
            join documents d on d.id = c.document_id
            where d.status = 'ready' and length(c.content) > 200
            order by random()
            limit %s
            """,
            (args.limit,),
        )
        chunks = cur.fetchall()

        if not chunks:
            sys.exit("No ready document chunks found — upload and index some documents first.")

        print(f"Pulled {len(chunks)} candidate chunks.")

        # For sampling negatives: id -> (document_id, content), grouped by document too.
        by_document: dict[str, list[tuple[str, str]]] = {}
        for chunk_id, doc_id, content in chunks:
            by_document.setdefault(doc_id, []).append((chunk_id, content))

        all_chunks = [(cid, did, content) for cid, did, content in chunks]

    written = 0
    with open(args.out, "w", encoding="utf-8") as f:
        for i, (chunk_id, doc_id, content) in enumerate(all_chunks, start=1):
            print(f"[{i}/{len(all_chunks)}] generating question…", end=" ", flush=True)
            question = call_gemini(args.api_key, content)
            time.sleep(args.sleep)

            if not question:
                print("skipped (no question generated)")
                continue
            print("ok" if args.quiet else f'"{question[:70]}"')

            f.write(json.dumps({"question": question, "passage": content, "label": 1}) + "\n")
            written += 1

            # Negative #1: a chunk from a different document entirely.
            other_docs = [d for d in by_document if d != doc_id]
            if other_docs:
                neg_doc = random.choice(other_docs)
                _, neg_content = random.choice(by_document[neg_doc])
                f.write(json.dumps({"question": question, "passage": neg_content, "label": 0}) + "\n")
                written += 1

            # Negative #2 (harder): a different chunk from the SAME document,
            # when one exists — topically close but not the right passage.
            same_doc_others = [c for c in by_document[doc_id] if c[0] != chunk_id]
            if same_doc_others:
                _, neg_content = random.choice(same_doc_others)
                f.write(json.dumps({"question": question, "passage": neg_content, "label": 0}) + "\n")
                written += 1

    print(f"\nWrote {written} labeled pairs to {args.out}")


if __name__ == "__main__":
    main()
